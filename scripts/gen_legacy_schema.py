#!/usr/bin/env python3
"""Generate src/legacy/schema.rs from mavlink XML message definitions."""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

def main(xml_dir: Path, out: Path, root_xml: str = "ardupilotmega.xml") -> None:
    bitmasks = {}
    messages = {}
    all_msgs = set()
    loaded = set()

    def parse_file(name: str) -> None:
        if name in loaded:
            return
        loaded.add(name)
        path = xml_dir / name
        if not path.exists():
            raise SystemExit(f"missing {path}")
        root = ET.fromstring(path.read_text(encoding="utf-8"))
        for inc in root.findall("include"):
            parse_file(inc.text.strip())
        for enum in root.iter("enum"):
            ename = enum.get("name")
            if enum.get("bitmask") != "true":
                continue
            entries = []
            for entry in enum.findall("entry"):
                val = entry.get("value")
                if val is None:
                    continue
                n = int(val, 16) if val.lower().startswith("0x") else int(val)
                entries.append((entry.get("name"), n))
            bitmasks[ename] = entries
        for msg in root.iter("message"):
            mname = msg.get("name")
            all_msgs.add(mname)
            fields = {}
            for field in msg.findall("field"):
                ftype = field.get("type", "")
                fname = field.get("name")
                enum = field.get("enum")
                m = re.match(r"char\[(\d+)\]", ftype)
                if m:
                    fields[fname] = ("char", int(m.group(1)))
                elif enum:
                    fields[fname] = ("enum", enum)
            if fields:
                messages[mname] = fields

    parse_file(root_xml)
    for mname, fields in list(messages.items()):
        for fname, kind in list(fields.items()):
            if kind[0] == "enum":
                if kind[1] in bitmasks:
                    fields[fname] = ("flags", kind[1])
                else:
                    del fields[fname]
        if not fields:
            del messages[mname]

    lines = [
        "// @generated by scripts/gen_legacy_schema.py from mavlink message definitions",
        "// Do not edit by hand.",
        "",
        "#[derive(Debug, Clone, Copy)]",
        "pub enum FieldKind {",
        "    CharArray(usize),",
        "    Bitflags(&'static str),",
        "}",
        "",
        "pub fn field_kind(message: &str, field: &str) -> Option<FieldKind> {",
        "    match (message, field) {",
    ]
    for mname in sorted(messages):
        for fname in sorted(messages[mname]):
            kind = messages[mname][fname]
            if kind[0] == "char":
                lines.append(
                    f'        ("{mname}", "{fname}") => Some(FieldKind::CharArray({kind[1]})),'
                )
            else:
                lines.append(
                    f'        ("{mname}", "{fname}") => Some(FieldKind::Bitflags("{kind[1]}")),'
                )
    lines += ["        _ => None,", "    }", "}", ""]
    lines += [
        "pub fn bitflag_entries(enum_name: &str) -> Option<&'static [(&'static str, u64)]> {",
        "    match enum_name {",
    ]
    for ename in sorted(bitmasks):
        entries = bitmasks[ename]
        if not entries:
            continue
        lines.append(f'        "{ename}" => Some(&[')
        for n, v in entries:
            lines.append(f'            ("{n}", {v}),')
        lines.append("        ]),")
    lines += ["        _ => None,", "    }", "}", ""]
    lines += ["pub fn is_message_name(name: &str) -> bool {", "    match name {"]
    for mname in sorted(all_msgs):
        lines.append(f'        "{mname}" => true,')
    lines += ["        _ => false,", "    }", "}"]
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({out.stat().st_size} bytes)")

if __name__ == "__main__":
    xml_dir = Path(sys.argv[1])
    out = Path(sys.argv[2])
    main(xml_dir, out)
